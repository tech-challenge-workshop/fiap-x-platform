#!/usr/bin/env node
/**
 * Produces db/create-database.sql, the database creation script the challenge
 * asks for as a deliverable.
 *
 * It is GENERATED, never hand-edited. A script maintained beside migrations
 * drifts from them, and the drift stays invisible until an evaluator runs it.
 * The source of truth is each service's own migrations, plus the bootstrap
 * that creates the schemas and their roles.
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const OUT = join(ROOT, 'db', 'create-database.sql');
const BOOTSTRAP = join(ROOT, 'db', 'init', '01-schemas.sql');

/** Each owning service, and the schema its migrations fill. */
const SERVICES = [
  {
    name: 'processing-catalog',
    schema: 'catalog',
    migrations: 'src/infrastructure/persistence/migrations',
  },
  {
    name: 'notification-service',
    schema: 'notification',
    migrations: 'src/notifications/infrastructure/persistence/migrations',
  },
];

/**
 * Pulls the SQL out of a migration's `up`.
 *
 * Migrations state their schema as `queryRunner.query(\`...\`)`, so the
 * template literals in `up` are the statements, in order. `down` is
 * deliberately ignored: this script creates, it never tears down.
 */
function extractUpStatements(source, file) {
  const upStart = source.indexOf('public async up(');
  if (upStart === -1) {
    throw new Error(`${file}: no up() found - cannot generate from it`);
  }
  const downStart = source.indexOf('public async down(');
  const upBody = source.slice(
    upStart,
    downStart === -1 ? source.length : downStart,
  );

  // `,?`: a call Prettier wraps onto its own lines ends with a trailing comma.
  const statements = [
    ...upBody.matchAll(/query\(\s*`([\s\S]*?)`\s*,?\s*\)/g),
  ].map((match) => match[1].trim());

  if (statements.length === 0) {
    throw new Error(`${file}: up() contains no SQL this script can read`);
  }
  // A call the pattern cannot read would otherwise vanish from the output
  // without a trace, and the script would stop matching the migrations.
  const calls = (upBody.match(/\.query\(/g) ?? []).length;
  if (calls !== statements.length) {
    throw new Error(
      `${file}: up() makes ${calls} query() calls but only ${statements.length} could be read`,
    );
  }
  return statements;
}

async function migrationsFor(service) {
  const dir = join(ROOT, '..', service.name, service.migrations);
  let files;
  try {
    files = await readdir(dir);
  } catch {
    throw new Error(
      `Missing migrations for ${service.name} at ${dir}. ` +
        'All five repositories must be checked out as siblings.',
    );
  }

  // Sorted by name: TypeORM's timestamp prefix is the order they must run in.
  const migrations = files
    .filter((f) => f.endsWith('.ts') && !f.startsWith('._'))
    .sort();

  if (migrations.length === 0) {
    throw new Error(`No migrations found for ${service.name} in ${dir}`);
  }

  const blocks = [];
  for (const file of migrations) {
    const source = await readFile(join(dir, file), 'utf8');
    blocks.push({ file, statements: extractUpStatements(source, file) });
  }
  return blocks;
}

async function main() {
  const bootstrap = await readFile(BOOTSTRAP, 'utf8');

  const parts = [
    '-- FIAP X - database creation script',
    '--',
    '-- GENERATED by scripts/generate-db-script.mjs. Do not edit by hand:',
    "-- regenerate it instead, or it stops describing the schema that runs.",
    '--',
    '-- Source: db/init/01-schemas.sql, then each service\'s own migrations.',
    '--',
    '-- This creates the schema the services expect. It does NOT write',
    "-- TypeORM's migrations ledger, so a database created this way will have",
    '-- each service try to apply its migrations again on first start. Use it',
    '-- to inspect or provision the schema, not as a substitute for running',
    '-- migrations against a database the services will then own.',
    '',
    '-- ============================================================',
    '-- Schemas and least-privilege roles',
    '-- ============================================================',
    '',
    bootstrap.trim(),
    '',
  ];

  for (const service of SERVICES) {
    const blocks = await migrationsFor(service);
    parts.push(
      '-- ============================================================',
      `-- ${service.name} (schema: ${service.schema})`,
      '-- ============================================================',
      '',
      `SET search_path TO ${service.schema};`,
      '',
    );
    for (const block of blocks) {
      parts.push(`-- from ${block.file}`);
      for (const statement of block.statements) {
        parts.push(statement.endsWith(';') ? statement : `${statement};`, '');
      }
    }
  }

  parts.push('RESET search_path;', '');
  await writeFile(OUT, parts.join('\n'), 'utf8');
  console.log(`Wrote ${OUT}`);
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
